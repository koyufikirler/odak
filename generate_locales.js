for (const [lang, msgs] of Object.entries(locales)) {
  const dir = path.join(localesDir, lang);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir);
  const file = path.join(dir, 'messages.json');

  // Keep translations already on disk. A locale entry may only cover part of
  // the UI; replacing the file outright would silently reset the shared
  // strings to English.
  let existing = {};
  if (fs.existsSync(file)) {
    try {
      existing = JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (e) {}
  }

  const merged = { ...existing };
  for (const [key, value] of Object.entries(sharedMessages)) {
    // English is the source of truth and always follows sharedMessages.
    if (lang === 'en' || !(key in merged)) merged[key] = value;
  }
  for (const [key, value] of Object.entries(msgs)) {
    merged[key] = value;
  }
  for (const [key, value] of Object.entries(regionalMessages[lang] || {})) {
    merged[key] = value;
  }
  for (const [key, value] of Object.entries(statsMessages[lang] || {})) {
    merged[key] = value;
  }

  // The single "Türkiye" list was replaced by the 38 regional rulesets.
  delete merged.filterTurkiyeName;
  delete merged.filterTurkiyeDesc;

  fs.writeFileSync(file, JSON.stringify(merged, null, 2) + '\n');
}

